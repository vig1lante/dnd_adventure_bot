import { formatMeters } from "./format";

// Одно правило перевода на два сервиса (спека Р3): тексты совпадают с units.meters_text движка
// и его таблицей в test_units.py — 5 футов = 1,5 м, дробь через запятую, без «,0», без округления.
const ENGINE_TABLE = [
  [5, "1,5 м"],
  [10, "3 м"],
  [15, "4,5 м"],
  [30, "9 м"],
  [60, "18 м"],
  [80, "24 м"],
  [120, "36 м"],
  [320, "96 м"],
  [2.5, "0,75 м"],
  [7.5, "2,25 м"],
  [0.5, "0,15 м"],
  [3, "0,9 м"],
  [0, "0 м"],
] as const;

describe("formatMeters: футы сервера → метры для игрока", () => {
  test.each(ENGINE_TABLE)("%s фт → «%s», как у движка", (feet, text) => {
    expect(formatMeters(feet)).toBe(text);
  });

  test("ошибка округления float не попадает в текст", () => {
    // Во float 3 × 0,3 = 0,8999999999999999, а 0,1 × 3 / 10 = 0,030000000000000006 и
    // 0,7 × 3 / 10 = 0,20999999999999996; движок печатает «0,9 м», «0,03 м» и «0,21 м».
    expect(formatMeters(3)).toBe("0,9 м");
    expect(formatMeters(1)).toBe("0,3 м");
    expect(formatMeters(0.1)).toBe("0,03 м");
    expect(formatMeters(0.7)).toBe("0,21 м");
  });

  test.each([
    [25, "7,5 м"],
    [35, "10,5 м"],
    [150, "45 м"],
    [600, "180 м"],
    [1000, "300 м"],
    [5280, "1584 м"],
  ] as const)(
    "дальности и большие числа — как у движка, без разрядных пробелов: %s фт → «%s»",
    (feet, text) => {
      expect(formatMeters(feet)).toBe(text);
    },
  );
});
