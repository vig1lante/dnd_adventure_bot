"""Перевод расстояний SRD в метры для текста людям и модели (спека DND-2, Р3).

Движок хранит числа SRD в футах, как в правилах (скорость 30, дальность лука 80/320), и
считает по ним; всё, что читают игроки и модель, пишется в метрах по правилу
5 футов = 1,5 м: 30 → «9 м», 80/320 → «24/96 м». Webapp переводит числа по тому же правилу.
"""


def meters(feet: int | float) -> float:
    """Метры для расстояния в футах: 5 → 1.5, 30 → 9.0."""
    # Умножение на 3 и деление на 10 вместо × 0.3: 3 × 0.3 во float даёт 0.8999999999999999.
    return feet * 3 / 10


def _number(feet: int | float) -> str:
    """Число метров по-русски: запятая, без хвоста «,0» — «1,5», «9»."""
    return f"{meters(feet):g}".replace(".", ",")


def meters_text(feet: int | float) -> str:
    """Расстояние в футах текстом в метрах: 5 → «1,5 м», 30 → «9 м»."""
    return f"{_number(feet)} м"


def meters_text_pair(normal: int | float, long: int | float) -> str:
    """Обычная и большая дальность оружия одной строкой: (80, 320) → «24/96 м»."""
    return f"{_number(normal)}/{_number(long)} м"
