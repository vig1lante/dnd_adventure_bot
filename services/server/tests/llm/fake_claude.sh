#!/bin/sh
# Общая обёртка `claude` для тестов: запускает имитатор fake_claude.py.
#
# Тест не пишет свой исполняемый скрипт, а кладёт в свою папку ссылку `claude` на этот файл и
# рядом `fake_claude.env`: в нём `python` и `script` (чем и что запускать) и `export` переменных
# имитатора. Новый исполняемый файл macOS проверяет при первом запуске (~0.2 с на каждый тест),
# а этот файл проверяется один раз — ссылки на него запускаются сразу.
. "$(dirname "$0")/fake_claude.env"
exec "$python" "$script" "$@"
